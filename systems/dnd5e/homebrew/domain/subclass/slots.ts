/** Derived homebrew progression, not an SRD single-class progression. */
export function thirdCasterSlots(level: number, table: readonly (readonly number[])[] = MULTICLASS_SLOTS): number[] {
  if (!Number.isInteger(level) || level < 3 || level > 20) throw new RangeError("Third caster level must be 3–20");
  return table[Math.ceil(level / 3) - 1].slice(0, 4);
}
